def calculate_sha256(file_path):
    """Streams file in 64KB blocks in raw binary mode to prevent RAM exhaustion and line-ending mutations."""
    sha256_hash = hashlib.sha256()
    try:
        with open(file_path, "rb") as f:
            for byte_block in iter(lambda: f.read(65536), b""):
                sha256_hash.update(byte_block)
        return sha256_hash.hexdigest().lower().strip()
    except FileNotFoundError:
        return None
    except PermissionError:
        return "PERMISSION_DENIED"


def verify_kit_integrity(directory_path=".", expected=None, one_of=None):
    """Audits required files. Missing files and hash mismatches both fail closed.

    `expected` defaults to OFFICIAL_HASHES. Every name in it must exist and match.
    `one_of` defaults to TAILS_ONE_OF when `expected` is omitted. At least one of
    those names must exist and match. Pass one_of={} from tests that supply their
    own required set.
    """
    print("\n" + "=" * 50)
    print("      PLEBUM DOMINIUM FILE INTEGRITY AUDIT      ")
    print("=" * 50)

    table = OFFICIAL_HASHES if expected is None else expected
    alternatives = TAILS_ONE_OF if one_of is None and expected is None else (one_of or {})
    missing = []
    mismatches_detected = False

    def check(target_file, expected_hash):
        nonlocal mismatches_detected
        full_path = os.path.join(directory_path, target_file)
        if not os.path.exists(full_path):
            missing.append(target_file)
            return
        print(f"\nChecking: {target_file}...")
        calculated = calculate_sha256(full_path)
        if calculated == "PERMISSION_DENIED":
            print("❌ [ERROR] Cannot read file. Check Linux permissions.")
            mismatches_detected = True
        elif calculated == expected_hash.lower().strip():
            print("✅ [OK] File Verified Perfectly.")
        else:
            print("❌ [CRITICAL FAILURE] HASH MISMATCH DETECTED!")
            print(f"   Expected: {expected_hash}")
            print(f"   Calculated: {calculated}")
            mismatches_detected = True

    for target_file, expected_hash in table.items():
        check(target_file, expected_hash)

    if alternatives:
        present = [name for name in alternatives if os.path.exists(os.path.join(directory_path, name))]
        if not present:
            missing.append("one of: " + ", ".join(alternatives))
        else:
            for name in present:
                check(name, alternatives[name])

    if missing:
        print("\nERROR: Missing required files:")
        for name in missing:
            print(f"  - {name}")
        print("Verification FAILED.")
        sys.exit(1)

    if mismatches_detected:
        print("\n" + "!" * 50)
        print(" [CRITICAL AMBER ALERT] SECURITY COMPROMISE POSSIBLE ")
        print(" One or more files do not match the pinned SHA-256 hashes.")
        print(" This script does not check signatures.")
        print(" ACTION REQUIRED: Format/wipe this flash drive entirely.")
        print(" Re-download the official tools from a trusted internet connection.")
        print("Verification FAILED.")
        print("!" * 50 + "\n")
        sys.exit(1)

    print("\nSUCCESS: Every required file was present and matched.")
    print("   Signatures are a separate check. This script does not do them.")
    print("=" * 50 + "\n")
    return 0


