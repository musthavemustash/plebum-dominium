def clean_binary(s: str) -> str:
    """Remove whitespace and keep only 0s and 1s."""
    cleaned = "".join(c for c in s if c in "01")
    if not cleaned:
        raise ValueError("No valid binary digits (0 or 1) found")
    stripped = s.replace(" ", "").replace("\n", "").replace("\t", "").replace("\r", "")
    if any(c not in "01" for c in stripped):
        extra = set(stripped) - set("01")
        raise ValueError(f"Invalid characters found: {extra}")
    return cleaned


def binary_to_bytes(bin_str: str) -> bytes:
    """Convert binary string to bytes. Pads left with zeros if needed."""
    remainder = len(bin_str) % 8
    if remainder != 0:
        bin_str = "0" * (8 - remainder) + bin_str
    return int(bin_str, 2).to_bytes(len(bin_str) // 8, byteorder="big")


def generate_mnemonic(raw_input: str):
    """
    Accept binary string of length >= 256.
    If longer than 256 bits → SHA-256 the whole thing → use resulting 256 bits.
    """
    entropy_bits = clean_binary(raw_input)
    original_length = len(entropy_bits)

    if original_length < 256:
        raise ValueError(
            f"Need at least 256 bits of entropy. You provided {original_length} bits."
        )

    if original_length > 256:
        print(f"Received {original_length} bits → hashing with SHA-256 to produce 256 bits...")
        data = binary_to_bytes(entropy_bits)
        hash_bytes = hashlib.sha256(data).digest()
        entropy_bits = bin(int.from_bytes(hash_bytes, "big"))[2:].zfill(256)
        print("Hashing complete.")
    else:
        print("Received exactly 256 bits. Using them directly.")

    # Final 256-bit entropy → bytes
    entropy_bytes = binary_to_bytes(entropy_bits)

    # BIP39 checksum = first 8 bits of SHA-256(entropy)
    hash_bytes = hashlib.sha256(entropy_bytes).digest()
    hash_bits = bin(int.from_bytes(hash_bytes, "big"))[2:].zfill(256)
    checksum = hash_bits[:8]

    full_bits = entropy_bits + checksum

    words = []
    for i in range(24):
        chunk = full_bits[i*11 : (i+1)*11]
        index = int(chunk, 2)
        words.append(WORDLIST[index])

    return words, original_length


